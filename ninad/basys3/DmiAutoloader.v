//
// One-button, program-selectable DMI autoloader for TinyRocketDMIConfig on
// Basys3.
//
// On a button press, plays back a fixed sequence of DMI (Debug Module
// Interface) write transactions that:
//   1. activate the debug module (dmcontrol.dmactive=1)
//   2. hold the hart in reset (dmcontrol.ndmreset=1) while we write memory
//   3. configure System Bus Access for 32-bit autoincrementing writes (sbcs)
//   4. set the target address to the DTIM base, 0x80000000 (sbaddress0)
//   5. write each word of the selected firmware to sbdata0 (each write
//      auto-triggers the actual bus transaction and autoincrements
//      sbaddress0 by 4)
//   6. arm a CLINT software interrupt for hart0 (still while in reset)
//   7. release ndmreset, so the hart restarts, takes the pending interrupt,
//      and boots the now-populated DTIM
//
// `prog_sel` (sampled once, at the moment the start button is pressed)
// picks which of NUM_PROGS pre-baked firmware images gets loaded. All
// programs' DMI transactions live concatenated in one flat array
// (ALL_ADDR/ALL_DATA); PROG_BASE[p]/PROG_LEN[p] say where program p starts
// and how many transactions it has. This whole ROM section (the flat
// array plus the base/length tables) is machine-generated by
// ninad/basys3/gen_dmi_rom_multi.py from each program's compiled
// firmware.mem -- never hand-typed, to eliminate transcription risk
// (a real bug earlier: a hand-copied word list was wrong and silently
// corrupted a program in-place; the fix was a script, verified byte-for-
// byte against objdump, not a human retyping hex).
//
// Register addresses and bit offsets below are taken from two authoritative
// sources, not guessed:
//   - DMI register addresses (dmcontrol=0x10, sbcs=0x38, sbaddress0=0x39,
//     sbdata0=0x3c) and the DMCONTROL/SBCS field *declaration order* (which
//     Chisel packs MSB-first, first-declared field = highest bit) come from
//     this repo's generators/rocket-chip/src/main/scala/devices/debug/dm_registers.scala
//   - The exact numeric bit offsets for dmcontrol/sbcs were cross-checked
//     against OpenOCD's own debug_defines.h (src/target/riscv/debug_defines.h).

